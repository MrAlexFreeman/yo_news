"use client";

import { useEffect } from "react";

/**
 * Предупреждение о несохранённых изменениях при закрытии или перезагрузке вкладки.
 *
 * **Что именно покрыто.** Событие `beforeunload` срабатывает, когда страница уходит совсем:
 * вкладку закрывают, нажимают F5, переходят по внешней ссылке. Это тот случай, который редакция
 * назвала первой причиной потери текста, и он же единственный, на который браузер даёт
 * предупредить системным диалогом.
 *
 * **Чего не покрыто.** Переход внутри сайта — клик по «Материалы» в шапке админки — страницу не
 * перезагружает, и `beforeunload` на нём не срабатывает вовсе. Это отдельный механизм
 * (перехват кликов по ссылкам и `confirm`), и делать его здесь было бы неправильно: перехват
 * ссылок в форме задевает и вставленные в материал адреса, и превью. Ограничение названо в
 * отчёте, а не спрятано.
 *
 * **Почему не свой текст.** Собственное сообщение браузеры показывают только со времён
 * Internet Explorer; сейчас текст задаёт браузер, а страница лишь просит спросить. Поэтому
 * диалог будет на языке браузера, и это не недоработка, а единственная доступная форма.
 */
export function useUnsavedChangesWarning(active: boolean): void {
  useEffect(() => {
    if (!active) return;

    const onBeforeUnload = (event: BeforeUnloadEvent) => {
      // Оба поля: `preventDefault` — современный стандарт, `returnValue` — то, что до сих пор
      // читает часть браузеров. Одного недостаточно ни там, ни там.
      event.preventDefault();
      event.returnValue = "";
    };

    window.addEventListener("beforeunload", onBeforeUnload);
    return () => window.removeEventListener("beforeunload", onBeforeUnload);
  }, [active]);
}
